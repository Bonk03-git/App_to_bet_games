-- Pełny zrzut schematu public (bez danych) jako jeden skrypt SQL.
--
-- Użycie: SQL Editor w Supabase -> wklej całe zapytanie -> Run -> skopiuj jedyną komórkę wyniku
-- do supabase/schema.sql. Uruchamiać po każdej zmianie w bazie, żeby schema.sql był aktualny.
--
-- Zrzut zawiera: rozszerzenia, typy enum, sekwencje, tabele, ograniczenia, indeksy, funkcje, widoki,
-- triggery (także na auth.users, jeśli wołają funkcję z public), RLS i polityki, uprawnienia
-- anon/authenticated (tabele, kolumny, funkcje) i tabele w publikacji Realtime.
--
-- Frazy 'create' || ' table' i 'alter' || ' table' są rozbite celowo: SQL Editor w Supabase wykrywa
-- tworzenie tabel w treści zapytania i dopisuje własne włączenie RLS, co kończy się błędem:
-- relation "public" does not exist.
--
-- NIE zawiera: danych (mecze, bonus_results, admins, ligi), schematów auth/storage, zadania pg_cron
-- (jest w supabase/cron.sql), sekretów Vault ani sekretów Edge Functions.

with
ext (sec, k, ddl) as (
  select 1, e.extname::text, format('create extension if not exists %I with schema %I;', e.extname, n.nspname)
  from pg_extension e
  join pg_namespace n on n.oid = e.extnamespace
  where e.extname <> 'plpgsql'
),
enums (sec, k, ddl) as (
  select 2, t.typname::text, format('create type public.%I as enum (%s);', t.typname,
    (select string_agg(quote_literal(en.enumlabel), ', ' order by en.enumsortorder)
     from pg_enum en where en.enumtypid = t.oid))
  from pg_type t
  join pg_namespace n on n.oid = t.typnamespace
  where n.nspname = 'public' and t.typtype = 'e'
),
seqs (sec, k, ddl) as (
  select 3, c.relname::text, format('create sequence if not exists public.%I;', c.relname)
  from pg_class c
  join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind = 'S'
    -- sekwencje kolumn identity powstają same z tabelą
    and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype = 'i')
),
tbls (sec, k, ddl) as (
  select 4, c.relname::text, format('create' || E' table public.%I (\n%s\n);', c.relname,
    (select string_agg(
        format('  %I %s%s%s%s',
          a.attname,
          format_type(a.atttypid, a.atttypmod),
          case a.attidentity
            when 'a' then ' generated always as identity'
            when 'd' then ' generated by default as identity'
            else '' end,
          case
            when a.attgenerated = 's' then ' generated always as (' || pg_get_expr(ad.adbin, ad.adrelid) || ') stored'
            when ad.adbin is not null then ' default ' || pg_get_expr(ad.adbin, ad.adrelid)
            else '' end,
          case when a.attnotnull then ' not null' else '' end),
        E',\n' order by a.attnum)
     from pg_attribute a
     left join pg_attrdef ad on ad.adrelid = a.attrelid and ad.adnum = a.attnum
     where a.attrelid = c.oid and a.attnum > 0 and not a.attisdropped))
  from pg_class c
  join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind in ('r', 'p')
),
cons (sec, k, ddl) as (
  -- klucze obce na końcu, gdy wszystkie tabele i klucze główne już istnieją
  select case when con.contype = 'f' then 6 else 5 end,
    c.relname || '.' || con.conname,
    format('alter' || ' table public.%I add constraint %I %s;', c.relname, con.conname, pg_get_constraintdef(con.oid))
  from pg_constraint con
  join pg_class c on c.oid = con.conrelid
  join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and con.contype in ('p', 'u', 'c', 'f', 'x')
),
idx (sec, k, ddl) as (
  select 7, ic.relname::text, pg_get_indexdef(i.indexrelid) || ';'
  from pg_index i
  join pg_class ic on ic.oid = i.indexrelid
  join pg_class c on c.oid = i.indrelid
  join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public'
    -- indeksy kluczy głównych i unikalnych powstają z ograniczeniami
    and not exists (
      select 1 from pg_constraint con
      where con.conindid = i.indexrelid and con.contype in ('p', 'u', 'x')
    )
),
funcs (sec, k, ddl) as (
  select 8, p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')', pg_get_functiondef(p.oid) || ';'
  from pg_proc p
  join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.prokind in ('f', 'p')
    -- pomijamy funkcje należące do rozszerzeń
    and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
),
views (sec, k, ddl) as (
  select 9, c.relname::text, format(E'create or replace view public.%I%s as\n%s', c.relname,
    case when c.reloptions is not null then ' with (' || array_to_string(c.reloptions, ', ') || ')' else '' end,
    pg_get_viewdef(c.oid, true))
  from pg_class c
  join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind = 'v'
),
trg (sec, k, ddl) as (
  select 10, c.relname || '.' || t.tgname, pg_get_triggerdef(t.oid) || ';'
  from pg_trigger t
  join pg_class c on c.oid = t.tgrelid
  join pg_namespace n on n.oid = c.relnamespace
  join pg_proc p on p.oid = t.tgfoid
  join pg_namespace pn on pn.oid = p.pronamespace
  where not t.tgisinternal and (n.nspname = 'public' or pn.nspname = 'public')
),
rls (sec, k, ddl) as (
  select 11, c.relname::text, format('alter' || ' table public.%I enable row level security;', c.relname)
  from pg_class c
  join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind in ('r', 'p') and c.relrowsecurity
),
pol (sec, k, ddl) as (
  select 12, tablename || '.' || policyname,
    format('create policy %I on public.%I as %s for %s to %s%s%s;',
      policyname, tablename, lower(permissive), lower(cmd), array_to_string(roles, ', '),
      case when qual is not null then ' using (' || qual || ')' else '' end,
      case when with_check is not null then ' with check (' || with_check || ')' else '' end)
  from pg_policies
  where schemaname = 'public'
),
tgr (sec, k, ddl) as (
  -- uprawnienia do tabel i widoków: najpierw wszystko odbieramy, potem nadajemy to, co jest w bazie
  select 13, c.relname || '.0', format('revoke all on public.%I from anon, authenticated;', c.relname)
  from pg_class c
  join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind in ('r', 'p', 'v')
  union all
  select 13, c.relname || '.1.' || r.rolname,
    format('grant %s on public.%I to %I;', string_agg(lower(a.privilege_type), ', ' order by a.privilege_type), c.relname, r.rolname)
  from pg_class c
  join pg_namespace n on n.oid = c.relnamespace
  cross join lateral aclexplode(c.relacl) a
  join pg_roles r on r.oid = a.grantee
  where n.nspname = 'public' and c.relkind in ('r', 'p', 'v') and r.rolname in ('anon', 'authenticated')
  group by c.relname, r.rolname
  union all
  -- uprawnienia tylko do wybranych kolumn (np. update wyniku meczu, select bez hasła ligi)
  select 13, c.relname || '.2.' || r.rolname || '.' || a.privilege_type,
    format('grant %s (%s) on public.%I to %I;', lower(a.privilege_type),
      string_agg(quote_ident(att.attname), ', ' order by att.attnum), c.relname, r.rolname)
  from pg_attribute att
  join pg_class c on c.oid = att.attrelid
  join pg_namespace n on n.oid = c.relnamespace
  cross join lateral aclexplode(att.attacl) a
  join pg_roles r on r.oid = a.grantee
  where n.nspname = 'public' and att.attnum > 0 and not att.attisdropped
    and r.rolname in ('anon', 'authenticated')
  group by c.relname, r.rolname, a.privilege_type
),
fgr (sec, k, ddl) as (
  select 14, p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ').0',
    format('revoke all on function public.%I(%s) from public, anon, authenticated;',
      p.proname, pg_get_function_identity_arguments(p.oid))
  from pg_proc p
  join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.prokind in ('f', 'p') and p.proacl is not null
    and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
  union all
  select 14, p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ').1.' || coalesce(r.rolname::text, 'public'),
    format('grant execute on function public.%I(%s) to %s;',
      p.proname, pg_get_function_identity_arguments(p.oid),
      case when a.grantee = 0 then 'public' else quote_ident(r.rolname) end)
  from pg_proc p
  join pg_namespace n on n.oid = p.pronamespace
  cross join lateral aclexplode(p.proacl) a
  left join pg_roles r on r.oid = a.grantee
  where n.nspname = 'public' and p.prokind in ('f', 'p')
    and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
    and (a.grantee = 0 or r.rolname in ('anon', 'authenticated'))
),
pub (sec, k, ddl) as (
  select 15, tablename::text, format('alter publication supabase_realtime add table public.%I;', tablename)
  from pg_publication_tables
  where pubname = 'supabase_realtime' and schemaname = 'public'
)
select
  '-- Schemat bazy Predykcje MŚ2026 (Supabase, schemat public) - zrzut z ' || to_char(now(), 'YYYY-MM-DD') || E'\n'
  || E'-- Wygenerowany przez supabase/dump_schema.sql. Bez danych, auth/storage, pg_cron (supabase/cron.sql) i sekretów.\n\n'
  || E'set check_function_bodies = false;\n\n'
  || string_agg(ddl, E'\n\n' order by sec, k) as schema
from (
  select * from ext
  union all select * from enums
  union all select * from seqs
  union all select * from tbls
  union all select * from cons
  union all select * from idx
  union all select * from funcs
  union all select * from views
  union all select * from trg
  union all select * from rls
  union all select * from pol
  union all select * from tgr
  union all select * from fgr
  union all select * from pub
) x;
